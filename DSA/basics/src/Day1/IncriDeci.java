package Day1;

public class IncriDeci {
	public static void main(String[] args) {
		int a=1;
//		post increment
		System.out.println(a++);
		System.out.println(a);
		System.out.println();
		
		int b=1;
		//pre increment
		System.out.println(++b);
		System.out.println(b);
		System.out.println();
		
		//post decrement
		int c=1;
		System.out.println(c--);
		System.out.println(c);
		System.out.println();
		
		//pre decrement
		int d=1;
		System.out.println(--d);
		System.out.println(d);
	}
}
